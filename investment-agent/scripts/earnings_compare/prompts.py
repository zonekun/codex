"""日本語決算資料比較プロンプトテンプレート."""

SYSTEM_PROMPT = """あなたは日本株の機関投資家向けアナリストです。
決算資料を読み込み、前の四半期と最新の四半期を定性的に比較分析します。

【分析方針】
- 数値の大小比較は行わない（定性的な変化・トーンの変化に着目する）
- 経営陣のコメント・見通し・リスク認識の変化を重視する
- 事業の方向性・戦略の変化を読み取る
- ポジティブ・ネガティブ両面を均等に報告する
- 推測・憶測は行わず、資料に記載された内容のみを根拠にする
- 日本語で簡潔に報告する"""

COMPARISON_PROMPT_TEMPLATE = """以下の2つの決算資料を比較分析してください。

═══════════════════════════════
【前の四半期の決算資料】
{prev_quarter_label}
─────────────────────────────
{prev_text}

═══════════════════════════════
【最新の四半期の決算資料】
{latest_quarter_label}
─────────────────────────────
{latest_text}

═══════════════════════════════
【分析指示】

以下の観点で前Qと最新Qを比較し、定性的な変化をレポートしてください。
数値の比較は不要です。経営陣のトーン・言葉の変化・強調点の移動に着目してください。

1. **事業環境認識の変化**
   前Qと最新Qで、経営陣の市場・競合・外部環境に対する認識はどう変わったか？

2. **重点施策・戦略の変化**
   取り組みの優先順位や戦略的な強調点はどのように変化したか？

3. **リスク認識の変化**
   言及されているリスク項目・懸念点に変化はあるか？新たに登場したリスクは？

4. **前向き・後ろ向きトーンの変化**
   全体的なトーン（慎重・強気・中立）は変化したか？具体的な文章で示すこと。

5. **特記事項**
   前Qには言及がなく、最新Qに初めて登場した重要な記述があれば報告する。

【出力形式】
各項目を200字程度で簡潔に記述してください。変化がない場合は「変化なし」と記載してください。
"""


def build_comparison_prompt(
    latest_text: str,
    prev_text: str,
    latest_quarter_label: str,
    prev_quarter_label: str,
) -> str:
    """比較プロンプトを組み立てる.

    Args:
        latest_text: 最新Q のテキスト（複数書類は結合済み）。
        prev_text: 前Q のテキスト（複数書類は結合済み）。
        latest_quarter_label: 最新Q のラベル（例: "2025-11-14 開示分"）。
        prev_quarter_label: 前Q のラベル（例: "2025-08-14 開示分"）。

    Returns:
        Ollama に渡すプロンプト文字列。
    """
    return COMPARISON_PROMPT_TEMPLATE.format(
        latest_text=latest_text,
        prev_text=prev_text,
        latest_quarter_label=latest_quarter_label,
        prev_quarter_label=prev_quarter_label,
    )
